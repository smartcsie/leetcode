def fix_file(filepath, difficulty):
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()
    if "難度：待補充" not in content:
        return "skip"
    new_content = content.replace(" * 難度：待補充", f" * 難度：{difficulty}", 1)
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(new_content)
    return "ok"


if __name__ == "__main__":
    ok = skip = not_found = 0
    for num, difficulty in DIFFICULTY.items():
        filename = f"Solution_{num}.cpp"
        filepath = os.path.join(BASE, filename)
        if not os.path.exists(filepath):
            not_found += 1
            continue
        result = fix_file(filepath, difficulty)
        if result == "ok":
            print(f"[OK]   {filename}  → {difficulty}")
            ok += 1
        else:
            skip += 1
    print(f"\n完成！OK:{ok}  SKIP:{skip}  NOT_FOUND:{not_found}")
