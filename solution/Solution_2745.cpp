/**
 * 題目：2745. Construct the Longest New String
 * 難度：待補充
 * 描述：給你三個整數 x, y, z，分別代表你可以使用的字串 "AA", "BB", "AB" 的數量。
 * 請你使用這些字串構造出一個最長的新字串，且不能包含子字串 "AAA" 或 "BBB"。
 * 返回這個最長新字串的長度。
 *
 * 時間複雜度：O(1)
 * 空間複雜度：O(1)
 *
 * 解法思路：
 * （貪心與規律推導）：
 * 1. 限制條件分析：
 * - 不能出現 "AAA" 或 "BBB"，意味著 "AA" 和 "BB" 不能直接連續出現（否則會違反規則）。
 * - 因此，"AA" 與 "BB" 必須交替出現，形成 "...AABBAABB..." 的圖樣。
 * 2. "AB" 的百搭特性：
 * - 字串 "AB" 既可以接在 "AA" 後面，也可以接在 "BB" 後面，甚至可以自成循環，它不會造成連續的 A 或 B 超標。
 * - 所以 `z` 個 "AB" 可以全部無條件塞進去。
 * 3. "AA" 與 "BB" 的配對平衡：
 * - 假設 `x` 是 "AA" 的數量，`y` 是 "BB" 的數量。它們必須成對交替使用（例如 AABB）。
 * - 如果 `x == y`，我們可以完美配對出 `min(x, y) * 2` 個區塊。
 * - 如果 `x != y`，多出來的那一方只能單獨多放一個（因為不能連續），所以總共可以配對出 `min(x, y) * 2 + 1` 個。
 * 4. 長度計算：
 * - 每個 "AA", "BB", "AB" 的長度都是 2。
 * - 因此最後的總長度 = `(總共可以用的區塊數 + z) * 2`。
 */

class Solution {
public:
    int longestString(int x, int y, int z) {
        // 取 x 和 y 的最小值，用來交替配對成 AABB
        const int mn = std::min(x, y);
        
        // 如果 x 和 y 數量相等，可以完美交替 (例如 AABBAABB)
        if (x == y) {
            return (mn * 2 + z) * 2;
        }
        
        // 如果 x 和 y 數量不等，其中一方可以多放一個 (例如 AABBAABBAA 或 BBAABBAABB)
        return (mn * 2 + 1 + z) * 2;
    }
};
