/**
 * 題目：670. Maximum Swap
 * 難度：Medium
 * 時間複雜度：O(D)，D 為數字的位數（內層迴圈最多 9 次，視為常數）
 * 空間複雜度：O(D)
 * 分類主題：greedy-digit-construction
 *
 * 解法說明：
 * 最多交換一次，要讓數字最大，就要把「靠前的某個較小位數」換成「靠後的較大位數」。
 * 貪心策略：從最高位開始找，第一個「後面存在比它大的數字」的位置，
 * 就跟「後面最大的那個數字（若有多個，取最後出現的）」交換。
 * 為此先記錄每個數字 0~9 最後一次出現的位置。
 */
class Solution {
public:
    int maximumSwap(int num) {
        // 個位數無法交換出更大的結果
        if(num < 10) return num;

        string s = to_string(num);

        // last[d] = 數字 d 在字串中「最後一次」出現的索引，沒出現過為 -1
        // 取最後一次出現是因為：要換到最小的位數權重上，才能讓高位的增益最大化、損失最小化
        vector<int> last(10, -1);
        for(int i = 0; i < s.size(); i++) last[s[i] - '0'] = i;

        // 由高位到低位掃描，第一個能被換大的位置就是最佳交換點
        for(int i = 0; i < s.size(); i++) {
            // 從 9 往下試到「比當前數字大」為止，優先找最大的候選
            for(int x = 9; x > (s[i] - '0'); x--) {
                // 候選數字 x 的最後出現位置必須在 i 之後，才是「把大數換到前面」
                if(last[x] > i) {
                    swap(s[last[x]], s[i]);
                    return stoi(s);  // 只能換一次，換完直接回傳
                }
            }
        }

        // 掃完都沒有可交換的（數字本身已是非遞增排列，如 9973），維持原數
        return num;
    }
};