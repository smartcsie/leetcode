/**
 * 題目：2605. Form Smallest Number From Two Digit Arrays
 * 難度：簡單 (Easy)
 * 分類主題：bit-manipulation-mask
 * 描述：給定兩個各自不含重複數字的一位數陣列 nums1、nums2，求能組成
 * 的最小整數，這個整數的每一位數字都必須來自其中一個陣列（可以只用
 * 一位數，也可以用兩位數各取一個）。
 *
 * 時間複雜度：O(1)（數字只有 1~9，陣列長度上限固定，掃描次數是常數）
 * 空間複雜度：O(1)（bitset 固定 10 個 bit）
 *
 * 解法思路：
 * （bitset 標記 + 由小到大掃描，核心觀察是：如果兩個陣列有共同數字，
 * 答案一定是「最小的那個共同數字」單獨一位數，一定比任何兩位數答案
 * 更小）：
 * 1. 用兩個 `bitset<10>`（`seen1`、`seen2`）分別記錄 `nums1`、
 *    `nums2` 裡出現過哪些數字，`.set(x)` 把對應的 bit 設成 1。
 * 2. 由小到大掃描 1 到 9：
 *    - **一旦發現某個數字兩邊都出現過**（`seen1.test(i) &&
 *      seen2.test(i)`），立刻回傳這個數字——因為是由小到大掃描，
 *      第一個找到的共同數字就是「最小的共同數字」，這個單一數字
 *      一定比任何兩位數組合更小（單一數字最大是 9，兩位數最小是
 *      10），可以直接提早結束，不用管還有沒有更大的共同數字。
 *    - 如果沒有共同數字，順便記錄 `mn[0]`（`nums1` 裡最小的數字）
 *      跟 `mn[1]`（`nums2` 裡最小的數字）——因為是由小到大掃描，
 *      第一次遇到某個陣列有這個數字時，就是該陣列的最小值，用
 *      `mn[0] == -1` 這個判斷確保只記錄第一次（最小的）。
 * 3. 如果整個掃描完都沒有共同數字，代表答案要用兩個陣列各自的最小
 *    數字組成兩位數。**組合順序很重要**：要把較小的數字放在十位、
 *    較大的放在個位，這樣組出來的兩位數才會最小（例如 mn[0]=3,
 *    mn[1]=7，應該組成 37 而不是 73）。
 * 4. 用三元運算子判斷 `mn[0]`、`mn[1]` 誰比較小，決定誰放十位、誰
 *    放個位，組成最終答案。
 */
class Solution {
public:
    int minNumber(vector<int>& nums1, vector<int>& nums2) {
        bitset<10> seen1;
        bitset<10> seen2;
        for(const int& x : nums1) seen1.set(x);
        for(const int& x : nums2) seen2.set(x);
        vector<int> mn(2, -1);
        for(int i = 1; i <= 9; i++) {
            if(seen1.test(i) && seen2.test(i)) return i;
            if(seen1.test(i) && mn[0] == -1) mn[0]= i;
            if(seen2.test(i) && mn[1] == -1) mn[1]= i;
        }
        return mn[0] < mn[1] ? 10 * mn[0] + mn[1] :  10 * mn[1] + mn[0];
    }
};