/**
 * 題目：3133. Minimum Array End (最小陣列末項)
 * 難度：中等 (Medium)
 * 描述：建構一個長度為 n 的嚴格遞增正整數陣列 nums，使得所有元素的
 *       AND 結果恰好為 x，回傳 nums[n-1]（最後一個元素）的最小可能值。
 *
 * 時間複雜度：O(1)
 * 空間複雜度：O(1)
 *
 * 解法思路：
 * 1. 關鍵觀察：x 中為 1 的位元，所有陣列元素都必須保留 (Fixed Bits of x Must Stay)：
 *    - 因為所有元素 AND 起來要等於 x，只要 x 某一位是 1，
 *      陣列裡每個元素在這一位也都必須是 1（否則 AND 結果那一位就會變成 0）。
 * 2. x 中為 0 的位元，才是可以自由運用的「空位」(Zero Bits of x are Free Slots)：
 *    - 這些空位可以自由填入 0 或 1，不影響 AND 結果仍然是 x，
 *      因此可以用這些空位來讓陣列遞增、逐一擺放更大的數字。
 * 3. 把 (n-1) 的二進位，依序填進這些空位 (Insert Bits of n-1 into Free Slots)：
 *    - 陣列的第一個元素就是 x 本身；後續每多一個元素，就等同於在這些空位上
 *      多塞入一個遞增的二進位數字。第 n 個元素（索引從 0 開始的第 n-1 個），
 *      對應的就是把 (n-1) 的二進位，由最低位到最高位，依序填入 x 中值為 0 的位元位置。
 * 4. 处理超出 31 個位元範圍後剩餘的部分 (Handle Remaining Bits Beyond Bit 30)：
 *    - 迴圈只處理位元 0 到 30；若 (n-1) 的位元數超過 x 中「0 位元的數量」，
 *      代表 (n-1) 剩餘還沒填完的部分，就直接接在第 31 位元（bit 31）之後，
 *      因為超過這個範圍必定是全新的、原本 x 沒有涉及的高位部分。
 */
class Solution {
public:
    long long minEnd(int n, int x) {
        --n;
        long long ans = x;
        for (int i = 0; i < 31; ++i) {
            if (x >> i & 1 ^ 1) {
                ans |= (n & 1) << i;
                n >>= 1;
            }
        }
        ans |= (1LL * n) << 31;
        return ans;
    }
};
