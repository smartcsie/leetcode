/**
 * 題目：976. Largest Perimeter Triangle
 * 難度：Easy
 * 描述：給定整數陣列 nums，每個數字代表一條邊長。
 *       從中選三條邊組成面積大於 0 的三角形，回傳最大的周長；
 *       若無法組成任何三角形，回傳 0。
 *
 * 分類主題：greedy-sorting-decision
 * 技巧：排序後由大到小檢查相鄰三個數, 三角形不等式只需檢查兩短邊之和大於最長邊
 *
 * 時間複雜度：O(N log N)，主要來自排序
 * 空間複雜度：O(1)（不計排序的額外堆疊）
 *
 * 解法思路：排序 + 貪心
 * 1. 三角形成立的條件（面積大於 0）：任意兩邊之和大於第三邊。
 *    排序後設三邊為 a <= b <= c，只需檢查 a + b > c，
 *    其餘兩個不等式（a + c > b、b + c > a）因為 c 最大，必然成立。
 * 2. 排序後由大到小，以 nums[i] 當最長邊，
 *    最有機會滿足 a + b > c 的兩條短邊，就是緊鄰在它下面的 nums[i - 1]、nums[i - 2]
 *    （比它們更小的組合，兩邊之和只會更小）。
 * 3. 如果 nums[i - 2] + nums[i - 1] <= nums[i]，
 *    代表 nums[i] 搭配任何兩條更短的邊都無法成立，直接放棄這條最長邊，i 往下移。
 * 4. 第一個成立的組合就是答案：
 *    - 由大到小檢查，最長邊越大周長越大，
 *    - 且對固定的最長邊，取緊鄰的兩條邊使周長最大。
 *    所以找到第一組就可以直接回傳。
 * 5. 都找不到回傳 0。
 * 6. 溢位檢查：題目限制 nums[i] <= 10^6，三邊相加最大 3 × 10^6，int 放得下。
 */
class Solution {
public:
    int largestPerimeter(vector<int>& nums) {
        sort(nums.begin(), nums.end());  // 由小到大排序
        int n = nums.size();

        // i 為最長邊的索引，至少要有 i - 1、i - 2 兩條短邊，所以 i >= 2
        for (int i = n - 1; i >= 2; i--) {
            // 兩條較短邊之和大於最長邊，即可組成三角形；這是目前最大的合法組合
            if (nums[i - 2] + nums[i - 1] > nums[i]) {
                return nums[i - 2] + nums[i - 1] + nums[i];
            }
        }
        return 0;  // 沒有任何三條邊能組成三角形
    }
};
