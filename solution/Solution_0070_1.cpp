/**
 * 題目：70. Climbing Stairs
 * 難度：簡單 (Easy)
 * 分類主題：dp-fibonacci
 * 描述：爬到第 n 階樓梯，每次可以爬 1 階或 2 階，求總共有幾種不同的
 * 爬法。
 *
 * 時間複雜度：O(N)
 * 空間複雜度：O(N)
 *
 * 解法思路：
 * （一維線性 DP，用完整的 dp 陣列記錄每一階的爬法數，是最直觀、
 * 沒有經過空間優化的原始版本，方便理解狀態轉移的全貌）：
 * 1. base case：n <= 2 時直接回傳 n（原因跟滾動變數版一樣：爬 1、2
 *    階的爬法數剛好就是 1、2）。
 * 2. dp[i] 代表「爬到第 i 階」總共有幾種爬法。先手動設定
 *    dp[1] = 1、dp[2] = 2 這兩個起始值，因為狀態轉移公式
 *    `dp[i] = dp[i-1] + dp[i-2]` 從第 3 階開始才有意義（需要用到
 *    前兩階的值），第 1、2 階沒有更早的資料可以參考，要單獨初始化。
 * 3. 狀態轉移：要爬到第 i 階，最後一步只能是「從第 i-1 階爬 1 階
 *    上來」或「從第 i-2 階爬 2 階上來」，把這兩種走法的爬法數加起來，
 *    就是爬到第 i 階的總爬法數——這正是費氏數列的遞迴關係。
 * 4. 從 i = 3 迴圈算到 i = n，逐步把 dp 陣列填滿，最終 dp[n] 就是
 *    答案。
 * 5. **跟滾動變數版的差異**：這版把每一階的爬法數都完整存進陣列
 *    （空間複雜度 O(N)），滾動變數版只保留「前兩階」的值（空間
 *    複雜度 O(1)）。兩者時間複雜度相同，這版比較適合初學時理解
 *    「dp 陣列長什麼樣子」，熟悉之後再優化成滾動變數版更省空間。
 */

class Solution {
public:
    int climbStairs(int n) {
        if(n <= 2) return n;
        vector<int> dp(n + 1);
        dp[1] = 1, dp[2] = 2;
        for(int i = 3; i <= n; i++) dp[i] = dp[i - 1] + dp[i - 2];
        return dp[n];
    }
};