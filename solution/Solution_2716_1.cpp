/**
 * 題目：2716. Minimize String Length
 * 難度：簡單 (Easy)
 * 分類主題：bit-manipulation-mask
 * 描述：給定一個字串 s，每次操作可以選擇一個「至少出現兩次」的字元，
 * 刪掉它的其中一次出現。可以做任意次操作，求最後能得到的最短字串
 * 長度。
 *
 * 時間複雜度：O(N)
 * 空間複雜度：O(1)
 *
 * 解法思路：
 * （Bitmask，這題的關鍵洞察是：不管字元出現幾次，最終都能被反覆刪到
 * 只剩一個——所以答案就是「字串裡有幾種不同的字元」，跟每個字元
 * 各自出現的次數完全無關）：
 * 1. **關鍵觀察**：只要一個字元出現次數 >= 2，就可以一直刪到剩 1 個
 *    （每次操作把出現次數減 1，重複操作到剩 1 個為止）。所以每種
 *    字元最終都會剩下恰好 1 個，答案 = 字串裡不同字元的種類數。
 * 2. `seen` 是一個 int 遮罩，用 `seen |= 1 << (c - 'a')` 把每個出現
 *    過的字元對應的 bit 設成 1——這是最基本的 bitmask 去重技巧，
 *    不管某個字元出現幾次，同一個 bit 只會被設定、不會重複累加。
 * 3. `__builtin_popcount(seen)` 直接數出 `seen` 裡有幾個 bit 是 1，
 *    就是字串裡不同字元的種類數，也就是答案。
 * 4. 這題完全不需要真的模擬刪除操作、也不需要統計每個字元的出現
 *    次數，想通「答案只跟字元種類數有關」這個洞察之後，程式碼變得
 *    非常簡短。
 */
class Solution {
public:
    int minimizedStringLength(string s) {
        int seen = 0;
        for(const char& c : s) seen |= 1 << (c - 'a');
        return __builtin_popcount(seen);
    }
};