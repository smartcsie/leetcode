/**
 * 題目：2390. Removing Stars From a String
 * 難度：Medium
 * 描述：給定含有小寫字母與 '*' 的字串 s。每個 '*' 會刪除它左邊最近的一個非星號字元，
 *       連同這個 '*' 一起移除。回傳處理完所有星號後的字串。
 *       題目保證每個 '*' 左邊一定有可刪除的字元。
 *
 * 分類主題：stack
 * 技巧：用字串本身當堆疊, top 指標原地覆寫, 遇到星號 top 退一格, 最後 substr 截出有效部分
 *
 * 時間複雜度：O(n)
 * 空間複雜度：O(1)（不計回傳的 substr；原地使用 s 當堆疊）
 *
 * 解法思路：堆疊（原地版）
 * 1. 「刪除左邊最近的字元」就是堆疊的後進先出：遇到字母就推入，遇到 '*' 就彈出。
 * 2. 不另外開堆疊，直接把 s 的前 top 格當作堆疊內容：
 *    - 遇到字母：寫到 s[top]，top 加 1（推入）。
 *    - 遇到 '*'：top 減 1（彈出，這格之後會被覆寫）。
 * 3. 寫入位置 top 一定不超過目前讀到的位置，所以覆寫不會蓋掉還沒讀的字元，
 *    而且 for (char c : s) 是以值拷貝每個字元，讀取與寫入互不干擾。
 * 4. 掃完後，s 的前 top 格就是答案，用 substr(0, top) 取出。
 * 5. top > 0 的判斷是防禦性寫法；題目保證每個星號左邊都有字元，所以不會發生 top 為 0 還遇到星號。
 */
class Solution {
public:
    string removeStars(string s) {
        int top = 0;  // 堆疊大小，也是下一個要寫入的位置
        for(char c : s) {
            if(top > 0 && c == '*') {
                top--;          // 彈出：刪掉左邊最近的字元
            }
            else s[top++] = c;  // 推入：字母直接寫到堆疊頂端
        }
        return s.substr(0, top);  // 前 top 格就是剩下的字元
    }
};