/**
 * 題目：1551. Minimum Operations to Make Array Equal
 * 難度：Medium
 * 時間複雜度：O(1)
 * 空間複雜度：O(1)
 * 分類主題：math-formula
 *
 * 解法說明：
 * 陣列為 arr[i] = 2i + 1（1, 3, 5, ..., 2n-1），一次操作可從某個元素 -1、另一個元素 +1，
 * 總和不變，所以最終每個元素都會等於平均值 n（總和 n² 除以 n 個元素）。
 *
 * 一次操作剛好能把 1 單位從「大於 n 的元素」搬到「小於 n 的元素」，
 * 所以最少操作數 = 所有「小於 n 的元素」需要補到 n 的差距總和。
 * 小於 n 的元素共有 m = floor(n / 2) 個（i = 0 ~ m-1），差距為 n - (2i + 1)：
 *   總和 = m * n - (1 + 3 + ... + (2m-1)) = m * n - m²  （前 m 個奇數和為 m²）
 *
 * 化簡：
 *   n 為偶數：m = n/2     → n²/2 - n²/4 = n²/4
 *   n 為奇數：m = (n-1)/2 → (n-1)/2 * (n+1)/2 = (n² - 1)/4
 * 兩種情況都等於 floor(n² / 4)，C++ 整數除法直接截斷，所以統一寫成 n * n / 4。
 */
class Solution {
public:
    int minOperations(int n) {
        // n 最大 10^4，n * n 最大 10^8，不會超出 int 範圍
        return n * n / 4;
    }
};