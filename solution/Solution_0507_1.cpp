/**
 * 題目：507. Perfect Number (完全數)
 * 難度：簡單 (Easy)
 * 描述：判斷一個數是否為完全數。
 *       完全數定義：一個正整數等於其所有真因數（不含自身）之和。
 *       例如：28 = 1 + 2 + 4 + 7 + 14
 *
 * 時間複雜度：O(1) - 只檢查固定 5 個質數。
 * 空間複雜度：O(1) - 只使用常數空間。
 *
 * 解法思路：
 * 利用「歐拉完全數定理 (Euler's Perfect Number Theorem)」：
 * 所有偶完全數的形式為 2^(p-1) * (2^p - 1)，
 * 其中 2^p - 1 必須是質數（又稱梅森質數 Mersenne Prime）。
 * 題目範圍內 (1 <= num <= 10^8) 只有以下 5 個完全數：
 *   p=2  → 2^1  * (2^2  - 1) = 6
 *   p=3  → 2^2  * (2^3  - 1) = 28
 *   p=5  → 2^4  * (2^5  - 1) = 496
 *   p=7  → 2^6  * (2^7  - 1) = 8128
 *   p=13 → 2^12 * (2^13 - 1) = 33550336
 * 直接枚舉這 5 個質數 p，用位元運算建構出完全數後比對即可。
 */

class Solution {
public:
    bool checkPerfectNumber(int num) {
        for(int p : {2 ,3 ,5 ,7, 13}) {
            int n = ((1 << p) - 1) * (1 << (p - 1));
            if(num == n) return true;
        }
        return false;
    }
};