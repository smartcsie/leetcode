/**
 * 題目：70. Climbing Stairs
 * 難度：簡單 (Easy)
 * 分類主題：dp-fibonacci
 * 描述：爬到第 n 階樓梯，每次可以爬 1 階或 2 階，求總共有幾種不同的
 * 爬法。
 *
 * 時間複雜度：O(N)
 * 空間複雜度：O(1)
 *
 * 解法思路：
 * （一維線性 DP，用兩個變數滾動更新，取代整個 dp 陣列，是這個
 * dp-fibonacci 分類最典型的空間優化寫法）：
 * 1. base case：n <= 2 時直接回傳 n（爬 1 階只有 1 種爬法；爬 2 階
 *    有「1+1」或「一次爬 2 階」共 2 種爬法，剛好答案就等於 n）。
 * 2. 狀態轉移的核心觀念：要爬到第 i 階，最後一步只能是「從第 i-1 階
 *    爬 1 階上來」或「從第 i-2 階爬 2 階上來」，所以爬法數
 *    dp[i] = dp[i-1] + dp[i-2]——這正是費氏數列的遞迴關係，這題其實
 *    就是換皮版的費氏數列。
 * 3. n1、n2 分別代表「上上一階」「上一階」的爬法數（對應 dp[i-2]、
 *    dp[i-1]），從第 3 階開始往上推：n3 = n1 + n2 算出目前這一階的
 *    爬法數，接著把 n1、n2 往前挪一格（n1 = n2、n2 = n3），準備算
 *    下一階。
 * 4. **不用開陣列的原因**：因為每一階只依賴「前兩階」的結果，不需要
 *    保留更早之前的資料，用兩個變數滾動更新就夠了，把空間複雜度從
 *    O(N) 壓到 O(1)。
 * 5. 迴圈跑到 i = n 結束，n3 就是最終答案。
 */

class Solution {
public:
    int climbStairs(int n) {
        if(n <= 2) return n;
        int n1 = 1, n2 = 2, n3;
        for(int i = 3; i <= n; i++) {
            n3 = n1 + n2;
            n1 = n2;
            n2 = n3;
        }
        return n3;
    }
};
