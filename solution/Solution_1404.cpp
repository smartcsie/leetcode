/**
 * 題目：1404. Number of Steps to Reduce a Number in Binary Representation to One
 * 描述：給你一個以二進位字串形式表示的數字 s。請你返回將它減到 1 所需要的步驟數：
 *       - 如果當前數字是偶數，將其除以 2。
 *       - 如果當前數字是奇數，將其加上 1。
 *       題目保證輸入的二進位字串代表的正整數很大，無法直接用標準整數型態儲存。
 * 
 * 解法思路（逆向位元模擬與進位追蹤 Reverse Simulation with Carry）：
 * 1. 從右向左逐位檢查：
 *    - 從字串的最後一個字元（最低有效位）開始往前遍歷到索引 1（保留最高位）。
 *    - 利用 `carry` 記錄當前位置受到的進位影響。
 * 2. 判斷奇偶與步驟累加：
 *    - 當前位的實際數值為 `bit = (s[i] - '0') + carry`。
 *    - **若 `bit` 為奇數**（`bit & 1 == 1`）：代表數字是奇數，根據規則需要先加 1（產生進位讓該位變成 0），這會消耗 1 步；接著除以 2（將整個二進位向右移位，對應到字串中就是往前一位），這又消耗 1 步。因此奇數總共需要 `ans += 2`，並將進位 `carry` 設為 1。
 *    - **若 `bit` 為偶數**（`bit & 1 == 0`）：代表數字是偶數，只需進行除以 2 的移位動作，消耗 1 步（`ans += 1`）。
 * 3. 處理最高位的收尾：
 *    - 當迴圈結束時，若最後還留有未消解的進位（`carry == 1`），代表最高位需要額外多做一次進位與相加操作，最後回傳 `ans + carry`。
 * 時間複雜度：O(N) - 單次遍歷模擬進位，從右到左處理。
 * 空間複雜度：O(1) - 僅使用常數空間。

 */

class Solution {
public:
    int numSteps(std::string s) {
        int ans = 0;
        int carry = 0;
        
        // 從最低位（右側）向左掃描到索引 1
        for (int i = s.size() - 1; i > 0; i--) {
            int bit = (s[i] - '0') + carry;
            
            // 若為奇數：需要「加 1」再「除以 2」，共 2 步，並產生進位
            if (bit & 1) {
                carry = 1;
                ans += 2; 
            } else { // 若為偶數：只需「除以 2」，共 1 步
                ans += 1;
            }
        }
        
        // 加上最後殘留的進位對最高位帶來的額外步驟
        return ans + carry;
    }
};
