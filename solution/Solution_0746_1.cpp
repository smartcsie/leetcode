/**
 * 題目：746. Min Cost Climbing Stairs
 * 難度：Easy
 * 描述：cost[i] 是踩上第 i 階要付的費用。付費後可以往上爬 1 階或 2 階，
 *       起點可以選第 0 階或第 1 階，目標是爬過最後一階（到達頂端）。
 *       回傳到達頂端的最小總費用。
 *
 * 分類主題：dp-linear
 * 技巧：一維 DP, 滾動變數只保留前兩階, 答案取最後兩階的較小值
 *
 * 時間複雜度：O(N)
 * 空間複雜度：O(1)
 *
 * 解法思路：線性 DP + 滾動變數
 * 1. 狀態：dp[i] = 「踩到第 i 階（含這階費用）」的最小總費用。
 * 2. 初始：可以從第 0 或第 1 階起跳，所以 dp[0] = cost[0]、dp[1] = cost[1]。
 * 3. 轉移：第 i 階只能從 i - 1 或 i - 2 階上來，
 *    dp[i] = cost[i] + min(dp[i - 1], dp[i - 2])。
 * 4. 頂端在最後一階之外，最後一步可以從倒數第一階或倒數第二階跨上去，
 *    所以答案是 min(dp[n - 1], dp[n - 2])。
 * 5. dp[i] 只依賴前兩項，用 n0、n1 兩個變數滾動即可，不需要整個陣列：
 *    n0 = dp[i - 2]、n1 = dp[i - 1]，算出 n2 = dp[i] 後整體往前移一格。
 * 6. 迴圈結束時，n0 = dp[n - 2]、n1 = dp[n - 1]，
 *    n = 2 時迴圈不會執行，直接回傳 min(cost[0], cost[1])，結果正確。
 */
class Solution {
public:
    int minCostClimbingStairs(vector<int>& cost) {
        int n0 = cost[0];  // dp[i - 2]：踩到前前一階的最小費用
        int n1 = cost[1];  // dp[i - 1]：踩到前一階的最小費用
        int n2;            // dp[i]：踩到目前這階的最小費用

        for(int i = 2; i < cost.size(); i++) {
            n2 = cost[i] + min(n0, n1);  // 從前一階或前前一階上來，取較便宜者
            n0 = n1;                     // 窗口往前滑一格
            n1 = n2;
        }

        // 最後一步可以從最後一階或倒數第二階跨到頂端
        return min(n0, n1);
    }
};