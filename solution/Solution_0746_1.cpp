/**
 * 題目：746. Min Cost Climbing Stairs
 * 難度：簡單 (Easy)
 * 分類主題：dp-fibonacci
 * 描述：給定一個陣列 cost，cost[i] 是從第 i 階往上爬所需付出的費用。
 * 每次可以爬 1 階或 2 階，可以從索引 0 或索引 1 開始爬，求到達樓梯頂端
 * （陣列長度之外的那一階）所需的最小總費用。
 *
 * 時間複雜度：O(N)
 * 空間複雜度：O(1)
 *
 * 解法思路：
 * （一維線性 DP，用三個滾動變數取代整個 dp 陣列，跟 70 題 Climbing
 * Stairs 是同一個轉移形狀，只是這裡多了「費用」要累加，而不是單純
 * 計數）：
 * 1. n0、n1、n2 分別代表「到達第 i-2 階」「第 i-1 階」「第 i 階」
 *    所需的最小費用（對應 dp[i-2]、dp[i-1]、dp[i]）。
 * 2. base case：n0 = n1 = 0，代表站在索引 0 或索引 1 都不用先付費就
 *    能出發（題目允許從這兩個位置任一個開始爬）。
 * 3. 狀態轉移：要到達第 i 階，只能從第 i-1 階跨 1 步、或第 i-2 階跨
 *    2 步上來，跨出去之前要先付「出發那一階」的費用，取兩者較小值：
 *    `n2 = min(n1 + cost[i-1], n0 + cost[i-2])`。
 * 4. 每算完一階，把 n0、n1 往前挪一格（n0 = n1、n1 = n2），準備算
 *    下一階，不用開陣列保留所有階的資料。
 * 5. 樓梯頂端是索引 n（陣列外面那一格，不用再付費），迴圈跑到
 *    i = n 結束，n2 就是到達頂端的最小總費用。
 * 6. `if (n == 0) return 0` 是邊界防護，但實際上題目保證
 *    `cost.length >= 2`，這個判斷式在官方測資裡不會被觸發到。
 */
class Solution {
public:
    int minCostClimbingStairs(vector<int>& cost) {
        int n = cost.size();
        if(n == 0) return 0;
        int n0 = 0, n1 = 0, n2;
        for(int i = 2; i <=n; i++) {
            n2 = min(n1 + cost[i - 1], n0 + cost[i - 2]);
            n0 = n1;
            n1 = n2;
        }
        return n2;
    }
};