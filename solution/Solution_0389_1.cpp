/**
 * 題目：389. Find the Difference
 * 難度：簡單 (Easy)
 * 分類主題：bit-manipulation-xor
 * 技巧：accumulate, bit_xor
 * 描述：字串 t 是把字串 s 打散重排後，再隨機插入一個額外的字元組成
 * 的。求這個多出來的額外字元是什麼。
 *
 * 時間複雜度：O(N)，N 是兩字串長度總和
 * 空間複雜度：O(N)（`u = s + t` 這個串接動作會複製出一份新字串）
 *
 * 解法思路：
 * （XOR 消消樂，用 `accumulate` 把整個串接後的字串一次摺疊成單一個
 * XOR 結果）：
 * 1. 先把 `s` 跟 `t` 串接成一個新字串 `u`（`u = s + t`），把兩個
 *    字串「合併成一個問題」處理。
 * 2. 用 `accumulate(u.begin(), u.end(), 0, bit_xor<int>())`，從初始值
 *    0 開始，把 `u` 裡每個字元依序 XOR 進去，最後得到一個整數結果。
 * 3. **核心原理**：`s` 裡出現的每個字元，在 `t` 裡也會出現同樣次數
 *    （因為 `t` 只是 `s` 打散重排、再多插入一個字元），這些「配對」
 *    的字元兩兩 XOR 會互相抵銷成 0（`x ^ x = 0`），XOR 具有交換律
 *    跟結合律，不管字元出現的順序或位置，成對的都會互相消掉；最後
 *    只剩下那個「沒有配對、落單」的額外字元留下來（`x ^ 0 = x`）。
 * 4. `accumulate` 的累加型別用 `int`（`bit_xor<int>()`），但函式
 *    回傳型別是 `char`——因為所有字元的 ASCII 值都遠小於 char 能
 *    表示的範圍，這裡的隱式型別轉換（int 窄化成 char）不會有任何
 *    資料遺失的問題，可以放心讓編譯器自動轉換。
 * 5. **跟另一版的差異**：這版用 `u = s + t` 先串接再一次 accumulate；
 *    另一版是分別對 `s`、`t` 各自 accumulate 一次，把上一次的結果
 *    當作下一次的初始值接續累加。兩者數學上完全等價（XOR 的結合律
 *    保證不管怎麼分組結果都一樣），但這版多花了 O(N) 的時間跟空間
 *    去複製出一份新字串 `u`，另一版不用額外複製、直接沿用已有的
 *    `s`、`t`，效能上略優——不過在這題資料量下差異可忽略，兩種寫法
 *    都收錄起來對照也不錯。
 */
class Solution {
public:
    char findTheDifference(string s, string t) {
        string u = s + t;
        return accumulate(u.begin(), u.end(), 0, bit_xor<int>());
    }
};