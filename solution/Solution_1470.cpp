/**
 * 題目：1470. Shuffle the Array
 * 難度：簡單 (Easy)
 * 描述：給定長度為 2n 的陣列 nums，格式為 [x1,...,xn,y1,...,yn]，
 *       回傳重排後的 [x1,y1,x2,y2,...,xn,yn]。
 *
 * 分類主題：bit-manipulation-mask
 * 技巧：位元打包 把兩個數存進同一個 int, 由後往前還原避免覆蓋, 原地操作
 *
 * 時間複雜度：O(N)
 * 空間複雜度：O(1)（不計回傳的拷貝）
 *
 * 解法思路：位元打包 + 由後往前還原
 * 1. 題目限制 1 <= nums[i] <= 1000，而 1000 < 1024 = 2^10，
 *    所以每個數字只佔 10 個位元，一個 32 位元 int 可以同時存兩個數。
 * 2. 第一輪（打包）：把 y_i = nums[i+n] 左移 10 位，用 OR 放進 nums[i] 的高位。
 *    此時 nums[i] 的低 10 位是 x_i，高位是 y_i。
 * 3. 第二輪（還原）：i 從 n-1 倒著走到 0：
 *    - y_i = nums[i] >> 10，寫到位置 2i+1
 *    - x_i = nums[i] & 1023（1023 = 二進位 10 個 1），寫到位置 2i
 * 4. 為什麼要由後往前：i >= 1 時寫入位置 2i、2i+1 都大於 i，
 *    只會覆蓋「已處理完」或「後半段已打包進前半」的格子，
 *    尚未處理的 nums[0..i-1] 不會被動到。
 *    i = 0 時先寫 nums[1] 再寫 nums[0]，nums[0] 在被改寫前已讀完高位。
 */
class Solution {
public:
    vector<int> shuffle(vector<int>& nums, int n) {
        // 打包：y_i 左移 10 位放高位，x_i 留在低 10 位
        for (int i = 0; i < n; i++) {
            nums[i] |= nums[i + n] << 10;
        }

        // 還原：由後往前，才不會覆蓋到還沒處理的打包資料
        for (int i = n - 1; i >= 0; i--) {
            nums[2 * i + 1] = nums[i] >> 10;   // 取出高位：y_i
            nums[2 * i] = nums[i] & 1023;      // 取出低 10 位：x_i（1023 = 0b1111111111）
        }
        return nums;
    }
};