/**
 * 題目：836. Rectangle Overlap (矩形重疊)
 * 難度：中等 (Medium)
 * 描述：給定兩個軸對齊的矩形 rec1、rec2（格式為 [x1, y1, x2, y2]，
 *       (x1,y1) 為左下角、(x2,y2) 為右上角），判斷兩者是否有重疊（重疊面積 > 0）。
 *
 * 時間複雜度：O(1) - 只需常數次比較運算。
 * 空間複雜度：O(1) - 只使用常數個變數。
 *
 * 解法思路：
 * 1. 從「不重疊」的反向條件推導 (Think in Terms of Non-Overlap)：
 *    - 兩個矩形不重疊，若且唯若其中一個矩形完全在另一個矩形的左邊、右邊、上面或下面
 *      （x 軸或 y 軸方向完全沒有交集）。
 * 2. x 軸方向需要有交集：
 *    - rec1[0] < rec2[2]（rec1 左邊界在 rec2 右邊界左側）且
 *      rec2[0] < rec1[2]（rec2 左邊界在 rec1 右邊界左側），
 *      兩者同時成立，才代表 x 軸方向確實有重疊區間。
 * 3. y 軸方向同理需要有交集：
 *    - rec1[1] < rec2[3] 且 rec2[1] < rec1[3]，確保 y 軸方向也確實有重疊區間。
 * 4. 使用嚴格不等式排除「僅邊緣相接」的情況：
 *    - 全部使用 < 而非 <=，確保兩矩形僅邊界相碰（重疊面積為 0）時，
 *      正確回傳 false（不算真正重疊）。
 * 5. 四個條件同時成立才算真正重疊：
 *    - x 軸與 y 軸方向都必須同時有正的重疊區間，矩形才算真正重疊
 *      （因為重疊面積 = x 方向重疊長度 × y 方向重疊長度，兩者都要大於 0）。
 */
class Solution {
public:
    bool isRectangleOverlap(vector<int>& rec1, vector<int>& rec2) { 
       return rec1[0] < rec2[2] && rec2[0] < rec1[2] && rec1[1] < rec2[3] && rec2[1] < rec1[3];
    }
};
