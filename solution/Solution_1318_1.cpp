/**
 * 題目：1318. Minimum Flips to Make a OR b Equal to c
 * 難度：中等 (Medium)
 * 分類主題：bit-manipulation-or
 * 描述：給定三個整數 a、b、c，每次操作可以翻轉 a 或 b 的某一個二進位
 * 位元，求最少需要翻轉幾次，才能讓 `a OR b == c`。
 *
 * 時間複雜度：O(log(max(a,b,c)))
 * 空間複雜度：O(1)
 *
 * 解法思路：
 * （逐位元獨立判斷，每一個 bit 位置的翻轉需求跟其他位置完全無關，
 * 這是這題能簡化成「逐 bit 掃描」的關鍵觀察）：
 * 1. 因為 OR 運算是逐位元獨立計算的，`a OR b` 在某一位是什麼，只跟
 *    `a`、`b` 在**那一位**的值有關，不會受其他位影響。所以可以把
 *    問題拆成「每一個 bit 位置分別算需要翻幾次」，再加總。
 * 2. 用 `while (a > 0 || b > 0 || c > 0)` 搭配 `>>= 1` 逐位元檢查，
 *    只要三者還有任何一個沒歸零，就代表還有位元要處理（用 OR 條件
 *    是因為三個數字的位元長度可能不同，要處理到最長的那個為止）。
 * 3. 每一輪只看最低位元（用 `& 1` 取出），依照 `c` 這一位是 0 還是
 *    1 分兩種情況：
 *    - **c 這一位是 0**：代表 `a OR b` 這一位也必須是 0，也就是 a、b
 *      這一位都要是 0。如果 a 這一位是 1，要翻 1 次；如果 b 這一位
 *      是 1，也要翻 1 次——兩個可能都要翻，所以是
 *      `(a & 1) + (b & 1)`（把兩個 0/1 值直接相加，最多貢獻 2 次）。
 *    - **c 這一位是 1**：代表 `a OR b` 這一位必須是 1，只要 a、b
 *      任一個這一位已經是 1 就滿足了，完全不用翻。只有當 a、b 這一位
 *      **都是 0** 的情況下，才需要翻其中一個（翻誰都可以，只要 1 次），
 *      所以是 `((a&1)==0) && ((b&1)==0)`（兩個條件都成立時，這個
 *      布林運算式的結果是 1，代表要翻 1 次；否則是 0，不用翻）。
 * 4. 把每個 bit 位置算出來的翻轉次數加總，就是最終答案。
 */
class Solution {
public:
    int minFlips(int a, int b, int c) {
        int count = 0;
        while(a > 0 || b > 0 || c > 0) {
            if((c & 1) == 0) count += (a & 1) + (b & 1);
            else count += ((a & 1) == 0) && ((b & 1) == 0);
            a >>= 1;
            b >>= 1;
            c >>= 1;
        }
        return count;
    }
};