/**
 * 題目：968. Binary Tree Cameras
 * 難度：困難 (Hard)
 * 描述：給定一棵二元樹，每個攝影機可以裝在任一節點上，能監控它自己、
 * 父節點、以及所有直接子節點。求監控整棵樹所需的最少攝影機數量。
 *
 * 時間複雜度：O(N)
 * 空間複雜度：O(H)，H 為樹高（遞迴堆疊）
 *
 * 解法思路：
 * （Tree DP，用「狀態編碼」代表每個節點目前的覆蓋情況，由下往上決定
 * 何時該裝攝影機）：
 * 1. 每個節點有三種狀態：0 = 未被覆蓋（自己沒攝影機，也沒有子節點/
 *    父節點裝攝影機罩住它）、1 = 已被覆蓋但自己沒裝攝影機（靠子節點
 *    的攝影機罩住）、2 = 自己裝了攝影機。
 * 2. 貪心 + Tree DP 的核心策略：從葉節點開始由下往上決定，能不裝
 *    攝影機就不裝，只有在「不裝的話子節點會沒人罩」的情況下才裝——
 *    這樣裝的攝影機數量一定最少，因為越晚（越靠近根）裝攝影機，
 *    覆蓋的節點數量potential越大，不會浪費。
 * 3. 狀態轉移（後序遍歷，先算完左右子節點再決定自己）：
 *    - 空節點視為「已覆蓋」（狀態 1），這樣葉節點的父節點才不會因為
 *      「空的另一側子節點沒被覆蓋」而被迫裝攝影機。
 *    - 如果左子節點或右子節點是「未被覆蓋」（狀態 0），代表自己必須
 *      裝攝影機才能罩住它們，回傳狀態 2，攝影機數 +1。
 *    - 否則如果左子節點或右子節點「裝了攝影機」（狀態 2），代表自己
 *      已經被子節點的攝影機罩住了，不用裝，回傳狀態 1。
 *    - 否則（左右子節點都是「已被覆蓋但沒攝影機」），代表自己沒被
 *      任何人罩住，回傳狀態 0（未被覆蓋，等父節點來處理）。
 * 4. 最後如果根節點本身是「未被覆蓋」（狀態 0，代表沒有父節點能幫它
 *    裝攝影機），要額外在根節點裝一台攝影機。
 */
class Solution {
    int cameras = 0;
    // 0 = 未被覆蓋, 1 = 已覆蓋但沒裝camera, 2 = 裝了camera
    int dfs(TreeNode* node) {
        if (!node) return 1;
        int left = dfs(node->left);
        int right = dfs(node->right);
        if (left == 0 || right == 0) {
            cameras++;
            return 2;
        }
        if (left == 2 || right == 2) return 1;
        return 0;
    }
public:
    int minCameraCover(TreeNode* root) {
        if (dfs(root) == 0) cameras++;
        return cameras;
    }
};
