/**
 * 題目：3014. Minimum Number of Pushes to Type Word I (輸入字串所需的最少按鍵次數 I)
 * 難度：中等 (Medium)
 * 描述：使用類似手機九宮格鍵盤，每個按鍵可以對應多個字母（最多 8 個字母共用同一個按鍵，
 *       按第 k 次循環切換到該按鍵上的第 k 個字母）。此版本假設 word 中的字母皆「不重複」，
 *       因此只需依照字串長度 n，分段計算每個字母所需的按鍵次數。
 *
 * 時間複雜度：O(1)
 * 空間複雜度：O(1)
 *
 * 解法思路：
 * 1. 分段計算 (Segment by Position)：
 *    - 因為每個按鍵最多容納 8 個字母，且字母無重複，
 *      故第 1~8 個字母只需按 1 次、第 9~16 個字母需按 2 次、
 *      第 17~24 個字母需按 3 次、第 25~26 個字母需按 4 次。
 * 2. 依字串長度 n 分四種情況處理：
 *    - n <= 8：全部字母都只需按 1 次，總按鍵數即為 n。
 *    - 8 < n <= 16：前 8 個字母各按 1 次（共 8 次），
 *      其餘 (n - 8) 個字母各按 2 次。
 *    - 16 < n <= 24：前 8 個按 1 次、中間 8 個按 2 次（共 8 + 16 = 24 次），
 *      其餘 (n - 16) 個字母各按 3 次。
 *    - n > 24（最多到 26）：前 24 個字母固定花費 8 + 16 + 24 = 48 次，
 *      其餘 (n - 24) 個字母各按 4 次。
 * 3. 累加各段花費，即為最終答案。
 *
 * 注意事項：
 *    - 此寫法直接以 word.size() 作為字母種類數量，
 *      隱含假設 word 中不含重複字母；
 *      若題目允許重複字母，應改採「統計詞頻 + 依頻率高低分配按鍵」的貪婪解法，
 *      否則計算結果可能不正確。
 */

class Solution {
public:
    int minimumPushes(string word) {
        int n = word.size();
        if (n <= 8) return n;
        else if (n <= 16) return 8 + 2 * (n - 8);
        else if (n <= 24) return 8 + 16 + 3 * (n - 16);
        return 8 + 16 + 24 + 4 * (n - 24); // 支援到 26
    }
};