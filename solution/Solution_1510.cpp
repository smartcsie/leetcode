/**
 * 題目：1510. Stone Game IV
 * 難度：困難 (Hard)
 * 描述：桌上有 n 顆石頭，兩個玩家輪流拿走「完全平方數」顆石頭
 * （1, 4, 9, 16...），拿到最後一顆石頭讓桌上變 0 顆的人獲勝。兩人都用
 * 最佳策略遊玩，求先手玩家是否能保證獲勝。
 *
 * 時間複雜度：O(N * √N)
 * 空間複雜度：O(N)
 *
 * 解法思路：
 * （最單純的一維 Game Theory DP，dp[i] 代表「桌上剩 i 顆石頭，輪到
 * 你選」時，你是否能保證獲勝）：
 * 1. dp[0] = false：桌上沒有石頭可拿，輪到你選代表你「拿不了」，
 *    對手在上一輪已經拿完最後一顆贏了，所以這個狀態對「你」來說是
 *    輸的（沒有東西可選）。
 * 2. 狀態轉移：枚舉所有可以拿的完全平方數 k²（k² <= i），拿走之後
 *    剩下 i - k² 顆，輪到對手選：
 *    - 如果 dp[i - k²] 是 false（代表在那個狀態下，輪到的那個人
 *      —也就是對手—會輸），那「你」選這個 k² 就能保證獲勝，
 *      dp[i] = true。
 *    - 只要找到一種能讓對手輸的選法就夠了，不用窮舉完所有選法
 *      （找到就 break）。
 * 3. 如果窮舉完所有可能的 k² 都沒辦法讓對手輸（每種選法對手都會贏），
 *    dp[i] 維持預設值 false（你會輸）。
 * 4. 答案是 dp[n]。
 */
class Solution {
public:
    bool winnerSquareGame(int n) {
        vector<bool> dp(n + 1, false);
        for (int i = 1; i <= n; ++i) {
            for (int k = 1; k * k <= i; ++k) {
                if (!dp[i - k * k]) {
                    dp[i] = true;
                    break;
                }
            }
        }
        return dp[n];
    }
};
