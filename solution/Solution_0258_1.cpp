/**
 * 題目：258. Add Digits (各位相加)
 * 難度：簡單 (Easy)
 * 描述：重複將一個非負整數的各位相加，直到結果為一位數。
 *
 * 解法思路：模擬
 * 1. 只要 num 還不是個位數（num >= 10），就持續處理。
 * 2. 每一輪用 while 迴圈拆解各位數字：
 *    - x % 10 取出最低位並累加到 y
 *    - x /= 10 移除最低位
 * 3. 拆解完後，用位數和 y 取代 num，進入下一輪判斷。
 * 4. num 變成個位數時結束，回傳 num。
 *
 * 時間複雜度：O(log n)
 *   第一輪需要 O(log n) 拆位數，之後 num 會急遽縮小
 *   （最大 int 約 10 位數，位數和最多 90，再下一輪最多 17...），
 *   總量由第一輪主導，可視為 O(log n)。
 * 空間複雜度：O(1)
 */
class Solution {
public:
    int addDigits(int num) {
        // 只要還不是個位數，就繼續把各位數字相加
        while (num >= 10) {
            int x = num;  // 暫存目前的數字，用來逐位拆解（保留 num 不被破壞）
            int y = 0;    // 累加各位數字的和
            // 拆解 x 的每一位
            while (x > 0) {
                y += x % 10;  // 取出最低位並累加
                x /= 10;      // 移除最低位
            }
            num = y;  // 用這一輪的位數和取代 num，繼續下一輪判斷
        }
        // 此時 num 已是個位數（0~9），即為答案
        return num;
    }
};