/**
 * 題目：2652. Sum Multiples (求和多個數的倍數)
 * 難度：簡單 (Easy)
 * 描述：給定正整數 n，回傳所有小於等於 n、且為 3、5 或 7 的倍數的整數總和。
 *
 * 時間複雜度：O(N) - 只需對 1 到 n 進行一次線性掃描。
 * 空間複雜度：O(1) - 只使用常數個變數（sum），不需額外配置記憶體。
 *
 * 解法思路：
 * 1. 暴力窮舉 1 到 n (Brute Force Enumeration)：
 *    - 由於題目資料規模通常很小（簡單題限制），直接從 1 迴圈遍歷到 n，
 *      逐一檢查每個數字即可，不需要額外的數學優化（如排容原理）。
 * 2. 檢查是否為 3、5 或 7 的倍數：
 *    - 對每個數字 i，只要能被 3、5 或 7 其中任一個整除，就符合條件。
 * 3. 累加符合條件的數字：
 *    - 將所有符合條件的 i 累加進 sum，最終回傳總和。
 */
class Solution {
public:
    int sumOfMultiples(int n) {
        int sum = 0;
        for(int i = 1 ;i <= n; i++) {
            if(i % 3 == 0 || i % 5 == 0 || i % 7 == 0) sum += i;
        }
        return sum;
    }
};
